"""The published profile's code path is byte-identical after the ledger hook was added.

The fixture tests/ledger/fixtures/published_sample.json was generated by the
unmodified code (before src/saadi/ledger existed): three chunks of one synthetic
document, the saved model replies (one clean, one with a mismatched anchor, one
unparseable), the exact prompts the strategy built, the parser outputs, and the
state snapshots. Rebuilding them with the current code must give the same bytes.
"""

from __future__ import annotations

import json
from pathlib import Path

from saadi.context_strategies import get_strategy
from saadi.context_strategies.hierarchical_summary import HIER_SYSTEM_PROMPT, HierarchicalSummaryStrategy
from saadi.core.state import drive_rollup_generator, init_discourse_state
from saadi.core.types import ChunkRecord
from saadi.prompts import load_prompt_profile

FIXTURE = Path(__file__).resolve().parent / "fixtures" / "published_sample.json"


def _replay(fixture: dict) -> tuple[list[dict], list[dict], list[dict]]:
    strategy = get_strategy("hierarchical", **fixture["strategy_kwargs"])
    assert strategy.ledger is None
    assert strategy._ledger_runtime is None
    assert strategy.name == "hierarchical_summary"
    state = init_discourse_state(hierarchy_levels=[1])
    prompts, outputs, snapshots = [], [], []
    for i, (text, reply) in enumerate(zip(fixture["chunks"], fixture["replies"], strict=True)):
        chunk = ChunkRecord(doc_id="fixture", chunk_id=f"fixture:{i}", chunk_index=i, raw_text=text)
        prompt = strategy.build_prompt(chunk, state)
        prompts.append({"system": prompt.system, "user": prompt.user})
        out, new_state, gen = strategy.apply_output_deferred(chunk, state, reply)
        if gen is not None:
            drive_rollup_generator(gen, None)
        outputs.append(out.to_dict())
        state = new_state
        snapshots.append(json.loads(json.dumps(state.snapshot())))  # the fixture went through JSON (int keys -> str)
    return prompts, outputs, snapshots


def test_published_prompts_and_parser_outputs_are_byte_identical() -> None:
    fixture = json.loads(FIXTURE.read_text(encoding="utf-8"))
    prompts, outputs, snapshots = _replay(fixture)
    assert prompts == fixture["prompts"], "the published prompt text changed"
    assert outputs == fixture["outputs"], "the published parser output changed"
    assert snapshots == fixture["snapshots"], "the published state update changed"
    assert [o["parser_status"] for o in outputs] == ["ok", "fallback", "failed"]


def test_published_system_prompt_still_matches_the_default_profile() -> None:
    assert load_prompt_profile("default").entity_system_prompt == HIER_SYSTEM_PROMPT
    assert (
        HierarchicalSummaryStrategy()
        .build_prompt(
            ChunkRecord(doc_id="d", chunk_id="d:0", chunk_index=0, raw_text="Nothing here."), init_discourse_state(hierarchy_levels=[1])
        )
        .system
        == HIER_SYSTEM_PROMPT
    )


def test_sync_apply_output_matches_deferred_on_the_fixture() -> None:
    fixture = json.loads(FIXTURE.read_text(encoding="utf-8"))
    strategy = get_strategy("hierarchical", **fixture["strategy_kwargs"])
    state = init_discourse_state(hierarchy_levels=[1])
    for i, (text, reply) in enumerate(zip(fixture["chunks"], fixture["replies"], strict=True)):
        chunk = ChunkRecord(doc_id="fixture", chunk_id=f"fixture:{i}", chunk_index=i, raw_text=text)
        out, state = strategy.apply_output(chunk, state, reply)
        assert out.to_dict() == fixture["outputs"][i]
        assert json.loads(json.dumps(state.snapshot())) == fixture["snapshots"][i]
